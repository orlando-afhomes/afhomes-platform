export type PaymentPurpose = "reservation" | "down_payment" | "installment" | "full";

export const PAYMENT_PURPOSES: readonly PaymentPurpose[] = ["reservation", "down_payment", "installment", "full"];
export const PAYMENT_METHODS = ["Cash", "Bank Transfer", "GCash", "Maya", "Card", "Cheque"] as const;
export type PaymentMethod = (typeof PAYMENT_METHODS)[number];

/** Logical lifecycle (07 section 9.3). Reversed and Refunded are linked adjustment events, not states. */
export type PaymentStatus = "submitted" | "under_review" | "verified" | "rejected" | "returned";

export type PaymentAdjustment = {
  id: string;
  kind: "reversal" | "refund";
  amountCentavos: number;
  date: string;
  reason: string;
  actorId: string;
};

type PaymentVersion = Pick<Payment, "purpose" | "amountCentavos" | "method" | "paidDate" | "referenceNo" | "documentNo" | "evidenceFileName">;

export type PaymentEvent = {
  at: string;
  actorId: string;
  event: string;
  note: string | null;
  previousVersion?: PaymentVersion;
};

/**
 * Payment record (07 section 8). The receipt file name is kept for display and
 * audit; the file itself is stored only as a browser-memory data URL for the
 * Finance viewer in this mock phase. Receipt numbers are never invented;
 * referenceNo is generated by the system and documentNo comes from the issued
 * document (cash receipts get a system OR number).
 */
export type Payment = {
  id: string;
  contractId: string;
  customerId: string;
  saleId: string | null;
  purpose: PaymentPurpose;
  amountCentavos: number;
  method: PaymentMethod;
  /** Business date on the receipt (YYYY-MM-DD, Asia/Manila). */
  paidDate: string;
  /** Accounting date for a receipt admitted after its own month closed. */
  countedDate?: string;
  /** System-generated payment reference (PAY-YYYYMMDD-NNNN); mandatory for every method. */
  referenceNo: string | null;
  /** Invoice, Official Receipt, Collection Receipt, or Acknowledgment Receipt number of the issued document. */
  documentNo?: string | null;
  evidenceFileName: string | null;
  /** Uploaded receipt image or PDF as a data URL (mock) or a private API address (api mode). */
  evidenceFileDataUrl?: string | null;
  /** Media type of the stored file, so the preview knows whether to show an image or a PDF link. */
  evidenceContentType?: string | null;
  /** Optional bank (list entry id) for bank transfers and cheques; absent on older receipts. */
  bankId?: string | null;
  submittedBy: string;
  submittedAt: string;
  status: PaymentStatus;
  verifiedBy: string | null;
  verifiedAt: string | null;
  /** Business date of Finance verification (Verified Collections are dated by this). */
  verifiedDate: string | null;
  decisionReason: string | null;
  adjustments: PaymentAdjustment[];
  history: PaymentEvent[];
};

export type ScheduleLineStatus = "paid" | "partial" | "due" | "overdue" | "upcoming";

export type ScheduleLineState = {
  seq: number;
  label: string;
  amountCentavos: number;
  dueDate: string | null;
  allocatedCentavos: number;
  status: ScheduleLineStatus;
};

/** Lifecycle of a receipt recorded without a matching contract (doc 07 section 11; F6.5). Never deleted. */
export type UnmatchedReceiptStatus = "unmatched" | "matched" | "rejected";

export type UnmatchedReceiptEvent = {
  at: string;
  actorId: string;
  event: string;
  note: string | null;
};

/**
 * A receipt the Clerk could not link to a contract: money arrived but no
 * matching payment obligation was found. It waits in the Finance exceptions
 * queue until Finance matches it to a contract or rejects it with a reason.
 * Amount, method, date and OR number are frozen at intake; matching only
 * assigns the contract (and the schedule purpose), never edits the money.
 */
export type UnmatchedReceipt = {
  id: string;
  amountCentavos: number;
  method: PaymentMethod;
  /** Business date on the receipt (YYYY-MM-DD, Asia/Manila). */
  paidDate: string;
  /** Clerk-entered OR number or bank reference; system-wide unique (doc 07 section 9.2). */
  orNumber: string;
  evidenceFileName: string | null;
  /** Uploaded receipt image or PDF as a data URL (mock) or a private API address (api mode). */
  evidenceFileDataUrl?: string | null;
  /** Media type of the stored file, so the preview knows whether to show an image or a PDF link. */
  evidenceContentType?: string | null;
  /** Why no matching contract or payment was found (required). */
  reason: string;
  submittedBy: string;
  submittedAt: string;
  status: UnmatchedReceiptStatus;
  /** Payment created by matching; null until matched. The record itself is kept. */
  matchedPaymentId: string | null;
  decisionReason: string | null;
  decidedBy: string | null;
  decidedAt: string | null;
  history: UnmatchedReceiptEvent[];
};

export type SubmitUnmatchedReceiptInput = {
  amountCentavos: number;
  method: PaymentMethod;
  paidDate: string;
  orNumber: string;
  reason: string;
  evidenceFileName?: string | null;
  /** File content as a data URL; kept in the browser-scoped mock store for the viewer. */
  evidenceDataUrl?: string | null;
};
